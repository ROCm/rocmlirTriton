#!/bin/sh

deps=$(ninja -t deps bin/mlir-mixr-fullc-test | grep lib/lib)
for dep in $deps; do
  dep=${dep%.a}
  case $dep in
    external/llvm-project/llvm/lib/lib*)
      dep=${dep#external/llvm-project/llvm/lib/lib}
      mlir_libs="$mlir_libs $dep"
      ;;
    lib/lib*)
      dep=${dep#lib/lib}
      rocmlir_libs="$rocmlir_libs $dep"
      ;;
  esac
done

echo "### DO NOT EDIT!";
echo "### Generated by scripts/get_fat_library_deps.sh";
echo "set(__mlir_libs"
echo $mlir_libs | tr ' ' $'\n' | sort
echo ")"
echo "set(__rocmlir_libs"
echo $rocmlir_libs | tr ' ' $'\n' | sort
echo ")"
