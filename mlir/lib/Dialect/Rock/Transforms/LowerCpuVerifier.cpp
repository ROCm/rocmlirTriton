// This pass lowers ONLY functions marked with "rock.cpu_verifier" attribute.
// These are CPU verification functions generated by rocmlir-gen that use
// tensor semantics and need to be bufferized before general host lowering.
//
// The pass isolates each marked function into a temporary module, runs the
// lowering pipeline on it, and then moves the lowered function back. This
// ensures that NO other functions in the module are affected.
//
//===----------------------------------------------------------------------===//

