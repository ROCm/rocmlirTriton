// This pass promotes the f16/bf16 numerator-sum (`reduce_sum(exp(...))`)
// produced by TOSA softmax patterns to f32, and opportunistically rewrites
// the two consumer chains we care about -- softmax normalization and
// log-sum-exp (LSE) -- in f32 as well.
//
// On the GPU path, `reduce_sum` is computed blockwise in f16 over small
// blocks (e.g. 32 elements), accumulating relatively little rounding error
// per block. Both the softmax normalization and the LSE computation
// (`(log2(l) + m)*ln2`) consume that blockwise sum.
//
// On the CPU path without this promotion, `reduce_sum` is a single-pass
// f16 reduction over the entire row (e.g. 384 or 1024 elements),
// accumulating much more rounding error than the GPU's blockwise approach.
// Every f16 consumer of that sum (the softmax `reciprocal` + normalize
// `mul`, and the LSE `log` + `add(max)`) then inherits and amplifies that
// error -- in particular `log` near 1 has very high relative sensitivity
// to its input.
//
// The rewrite is anchored on `tosa.reduce_sum` whose input is `tosa.exp`
// of an f16/bf16 tensor. Anchoring there (rather than on the softmax
// `mul`) means every downstream consumer benefits from the f32 sum
// automatically, and the original f16 `reduce_sum` is dead-code eliminated
// instead of being computed redundantly alongside the f32 one.
//
// For each consumer of the matched `reduce_sum`:
//   * Softmax tail (`reciprocal` -> `mul(exp, reciprocal)`) is rewritten
//     end-to-end in f32 with a single cast back to the original element
//     type before the downstream matmul -- preserving the original
//     softmax-only optimization.
//   * LSE chain (`log` and the `log + add(max)` follow-up) is rewritten in
//     f32 with the inputs cast up and the result cast back. This is the
//     LSE-specific extension: without it, `log` of the (now-precise) sum
//     would still be evaluated in f16 and lose most of the precision win.
//   * Anything else consuming the sum falls back to a single
//     `cast(reduce_sum_f32 to original-elem-type)` -- semantically
//     identical to the original f16 sum, just more accurate.
//
//===----------------------------------------------------------------------===//

